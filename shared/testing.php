<?php
declare(strict_types=1);

require_once __DIR__ . '/db.php';

function test_pdo(string $schemaFile): PDO
{
    $pdo = new PDO('sqlite::memory:', null, null, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
    sqlite_install_schema($pdo, $schemaFile);
    return $pdo;
}

final class TestRun
{
    private array $rows = [];
    private array $evidence = [];

    public function __construct(private string $title)
    {
    }

    public function submit(string $id, string $desc, array $input, string $expected, callable $process): array
    {
        $r = $process($input);
        if ($r['ok']) {
            $actual = 'accepted';
            $detail = 'inserted ' . ($r['ref'] ?? ('id ' . ($r['id'] ?? '?')));
        } else {
            $keys = array_keys($r['errors']);
            sort($keys);
            $actual = 'rejected:' . implode(',', $keys);
            $parts = [];
            foreach ($r['errors'] as $k => $v) {
                $parts[] = "$k: $v";
            }
            $detail = implode('; ', $parts);
        }
        $this->rows[] = [$id, $desc, $expected, $actual, $detail, $expected === $actual];
        return $r;
    }

    public function assert(string $id, string $desc, bool $condition, string $detail = ''): void
    {
        $this->rows[] = [$id, $desc, 'true', $condition ? 'true' : 'false', $detail, $condition];
    }

    public function evidence(string $caption, PDO $pdo, string $sql): void
    {
        $this->evidence[] = [$caption, $sql, $pdo->query($sql)->fetchAll()];
    }

    public function finish(string $mdPath): int
    {
        $failed = 0;
        $md = "# {$this->title} — test results\n\nGenerated by `tests/run_tests.php` on " . date('Y-m-d H:i:s') . ".\n\n";
        $md .= "| ID | Test case | Expected | Actual | Detail | Result |\n|---|---|---|---|---|---|\n";
        echo "\n{$this->title}\n" . str_repeat('=', strlen($this->title)) . "\n";
        foreach ($this->rows as [$id, $desc, $exp, $act, $detail, $pass]) {
            $failed += $pass ? 0 : 1;
            $md .= sprintf("| %s | %s | `%s` | `%s` | %s | %s |\n", $id, $desc, $exp, $act, str_replace('|', '\\|', $detail), $pass ? 'PASS' : '**FAIL**');
            printf("[%s] %-4s %s\n", $pass ? 'PASS' : 'FAIL', $id, $desc);
            if (!$pass) {
                echo "       expected: $exp\n       actual:   $act\n       detail:   $detail\n";
            }
        }
        $total = count($this->rows);
        $md .= "\n**Summary:** " . ($total - $failed) . " of $total passed.\n";
        foreach ($this->evidence as [$caption, $sql, $rows]) {
            $md .= "\n## Database evidence — $caption\n\n```sql\n$sql\n```\n\n";
            if (!$rows) {
                $md .= "_(no rows)_\n";
                continue;
            }
            $cols = array_keys($rows[0]);
            $md .= '| ' . implode(' | ', $cols) . " |\n|" . str_repeat('---|', count($cols)) . "\n";
            foreach ($rows as $row) {
                $md .= '| ' . implode(' | ', array_map(fn($v) => str_replace('|', '\\|', (string) $v), $row)) . " |\n";
            }
        }
        file_put_contents($mdPath, $md);
        echo "\n" . ($total - $failed) . " / $total passed. Report: $mdPath\n";
        return $failed === 0 ? 0 : 1;
    }
}

function template_select_values(string $html, string $name): array
{
    $pattern = '/<select[^>]*\bname="' . preg_quote($name, '/') . '"[^>]*>(.*?)<\/select>/s';
    if (!preg_match($pattern, $html, $block)) {
        return [];
    }
    preg_match_all('/<option\s+value="([^"]*)"/', $block[1], $m);
    $values = array_map(fn($v) => html_entity_decode($v, ENT_QUOTES | ENT_HTML5, 'UTF-8'), $m[1]);
    return array_values(array_filter($values, fn($v) => $v !== ''));
}

function template_radio_values(string $html, string $name): array
{
    $pattern = '/<input[^>]*type="radio"[^>]*name="' . preg_quote($name, '/') . '"[^>]*value="([^"]*)"/';
    preg_match_all($pattern, $html, $m);
    return array_map(fn($v) => html_entity_decode($v, ENT_QUOTES | ENT_HTML5, 'UTF-8'), $m[1]);
}
